"""Where the files of the project live.

The package carries the files it needs to work on its own: the weather
icons, the app icons and the catalogue of world places. They sit next to
the code, so an installed copy finds them wherever it is put.

The configuration is the other way round: it belongs to the machine that
runs the service, not to the package. It is looked for in this order:

1. the file named by ``--config``;
2. the file named by the ``ECMWF_WIDGET_CONFIG`` environment variable;
3. ``places.yml`` in the working directory;
4. ``config/places.yml`` of a checkout of the repository;
5. the starter configuration that comes with the package.
"""

from __future__ import annotations

import os
from pathlib import Path

__all__ = [
    "ASSETS_DIR",
    "CONFIG_ENV",
    "DATA_DIR",
    "DEFAULT_CONFIG_NAME",
    "ICON_DIR",
    "PACKAGED_CONFIG",
    "PACKAGE_DIR",
    "WORLD_PLACES",
    "default_config",
    "icon_dir",
]

#: The directory of the installed package.
PACKAGE_DIR = Path(__file__).resolve().parent

#: The images that travel with the package.
ASSETS_DIR = PACKAGE_DIR / "assets"

#: The weather icons of the widget.
ICON_DIR = ASSETS_DIR / "icons"

#: The data files of the package, among them the catalogue of world places.
DATA_DIR = PACKAGE_DIR / "data"

#: The catalogue of the world: every capital, a lot of major cities and
#: some notable peaks. It is generated by ``ecmwf-build-places``.
WORLD_PLACES = DATA_DIR / "world_places.yml"

#: The starter configuration, used when the machine has none of its own.
PACKAGED_CONFIG = DATA_DIR / "places.yml"

#: The name of the configuration file in the working directory.
DEFAULT_CONFIG_NAME = "places.yml"

#: The environment variable that names the configuration file.
CONFIG_ENV = "ECMWF_WIDGET_CONFIG"


def icon_dir() -> Path:
    """The directory the weather icons are read from.

    The ``ICON_DIR`` environment variable wins, so a set of icons can be
    put in a place of one's own choosing.
    """
    override = os.environ.get("ICON_DIR")
    if override:
        return Path(override).expanduser()
    return ICON_DIR


def _checkout_config() -> Path | None:
    """The configuration of a checkout of the repository, if there is one.

    The command is run from the repository, so the working directory and
    the ones above it are looked at for a checkout. The package itself may
    sit in one as well, when it was installed in editable mode.
    """
    here = Path.cwd()
    for directory in (here, *here.parents):
        candidate = directory / "config" / DEFAULT_CONFIG_NAME
        if candidate.is_file() and (directory / "pyproject.toml").is_file():
            return candidate

    repository = PACKAGE_DIR.parent.parent
    candidate = repository / "config" / DEFAULT_CONFIG_NAME
    if candidate.is_file():
        return candidate
    return None


def default_config() -> Path:
    """The configuration file to use when none was named.

    See the module docstring for the order the places are looked in.
    """
    named = os.environ.get(CONFIG_ENV)
    if named:
        return Path(named).expanduser()

    local = Path.cwd() / DEFAULT_CONFIG_NAME
    if local.is_file():
        return local

    checkout = _checkout_config()
    if checkout is not None:
        return checkout

    return PACKAGED_CONFIG
