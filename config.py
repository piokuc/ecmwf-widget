"""Configuration for the point forecast service.

The configuration lives in ``places.yml`` so it can be edited by hand. See
that file for the format; this module only loads and validates it.

The catalogue of world places lives in ``world_places.yml``, which is
generated by ``build_places.py``. The places to follow can be chosen with
the ``catalogue`` setting.
"""

from __future__ import annotations

import dataclasses
import os
from typing import Any

import yaml

import models
import parameters
from points import Place

__all__ = ["DEFAULT_CONFIG", "WORLD_PLACES", "Config", "load_config"]

DEFAULT_CONFIG = "places.yml"
WORLD_PLACES = "world_places.yml"


@dataclasses.dataclass
class Config:
    """Everything the service needs to run."""

    places: list[Place]
    catalogue: list[Place]
    parameters: list[str]
    pressure_levels: list[int]
    steps: list[int]
    models: list[models.Model]
    source: str
    fallback_sources: list[str]
    poll_interval: int
    database: str
    cache_dir: str
    method: str = "bilinear"
    lapse_rate: float = parameters.LAPSE_RATE
    keep_runs: int = 3
    path: str = DEFAULT_CONFIG

    @property
    def all_places(self) -> list[Place]:
        """The places that are followed, own ones first."""
        seen = set()
        result = []
        for place in list(self.places) + list(self.catalogue):
            if place.id in seen:
                continue
            seen.add(place.id)
            result.append(place)
        return result


def _as_list(value: Any) -> list:
    if value is None:
        return []
    if isinstance(value, str):
        return [value]
    return list(value)


def _resolve_parameters(value: Any) -> list[str]:
    """Turn the ``parameters`` setting into a concrete list of names.

    ``basic`` expands to the small default set, ``all`` to everything the
    0.1 deg tier publishes.
    """
    if value is None:
        value = "basic"

    if isinstance(value, str):
        value = [value]

    selection: list[str] = []
    for item in value:
        item = str(item).strip()
        if item == "basic":
            selection.extend(parameters.BASIC_PARAMETERS)
            selection.extend(parameters.BASIC_DERIVED)
        elif item == "all":
            selection.extend(parameters.available_sfc())
            selection.extend(parameters.available_pl())
            selection.extend(parameters.DERIVED)
        else:
            selection.append(item)

    # De-duplicate while keeping the order.
    seen: set[str] = set()
    unique = []
    for name in selection:
        if name not in seen:
            seen.add(name)
            unique.append(name)

    for name in unique:
        known = (
            name in parameters.PARAMETERS
            or name in parameters.PRESSURE_PARAMETERS
            or name in parameters.DERIVED
        )
        if not known:
            raise ValueError(
                f"unknown parameter {name!r}; known: " + ", ".join(sorted(parameters.names()))
            )
    return unique


def _load_places(path: str) -> list[Place]:
    """Read a places file into Place objects."""
    with open(path) as handle:
        raw = yaml.safe_load(handle) or {}

    places: list[Place] = []
    for entry in raw.get("places") or []:
        if "id" not in entry or "latitude" not in entry or "longitude" not in entry:
            raise ValueError(f"place entry is missing id/latitude/longitude: {entry!r}")
        places.append(
            Place(
                id=str(entry["id"]),
                name=str(entry.get("name", entry["id"])),
                latitude=float(entry["latitude"]),
                longitude=float(entry["longitude"]),
                elevation=(
                    float(entry["elevation"]) if entry.get("elevation") is not None else None
                ),
                timezone=str(entry.get("timezone", "UTC")),
                country=str(entry.get("country", "")),
                country_code=str(entry.get("country_code", "")),
                flag=str(entry.get("flag", "")),
                note=str(entry.get("note", "")),
                kind=str(entry.get("kind", "")),
            )
        )
    return places


def _select_catalogue(all_places: list[Place], selection: Any) -> list[Place]:
    """Pick the catalogue places to follow."""
    if selection is None:
        return []
    if isinstance(selection, str):
        selection = [selection]
    selection = [str(item) for item in selection]

    if "all" in selection:
        return list(all_places)
    if "none" in selection:
        return []

    wanted = set(selection)
    return [place for place in all_places if place.id in wanted]


def load_config(path: str | os.PathLike[str] = DEFAULT_CONFIG) -> Config:
    """Load and validate the configuration file."""
    path = os.fspath(path)
    with open(path) as handle:
        raw = yaml.safe_load(handle) or {}

    places = _load_places(path)

    catalogue_path = str(raw.get("world_places", WORLD_PLACES))
    catalogue_all = _load_places(catalogue_path) if os.path.exists(catalogue_path) else []
    catalogue = _select_catalogue(catalogue_all, raw.get("catalogue"))

    identifiers = [place.id for place in places]
    if len(set(identifiers)) != len(identifiers):
        raise ValueError("place ids must be unique")

    return Config(
        places=places,
        catalogue=catalogue,
        parameters=_resolve_parameters(raw.get("parameters")),
        pressure_levels=[int(level) for level in _as_list(raw.get("pressure_levels"))],
        steps=[int(step) for step in _as_list(raw.get("steps"))],
        models=models.resolve(raw.get("models", "ifs")),
        source=str(raw.get("source", "ecmwf")),
        fallback_sources=[str(s) for s in _as_list(raw.get("fallback_sources"))],
        poll_interval=int(raw.get("poll_interval", 900)),
        database=str(raw.get("database", "data/forecast.sqlite")),
        cache_dir=str(raw.get("cache_dir", "data/grib")),
        method=str(raw.get("method", "bilinear")),
        lapse_rate=float(raw.get("lapse_rate", parameters.LAPSE_RATE)),
        keep_runs=int(raw.get("keep_runs", 3)),
        path=path,
    )
